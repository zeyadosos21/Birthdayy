create or replace function public.add_todo(p_item text,p_code text)
returns public.birthday_todos
language plpgsql security definer set search_path=public,extensions
as $$
declare r public.birthday_todos;
begin
  if not public.verify_site_code(p_code) then raise exception 'Wrong birthday password'; end if;
  if char_length(trim(coalesce(p_item,'')))<2 then raise exception 'Write a to-do first'; end if;
  insert into public.birthday_todos(item) values(left(trim(p_item),180)) returning * into r;
  return r;
end; $$;
revoke execute on function public.add_todo(text,text) from public;
grant execute on function public.add_todo(text,text) to anon, authenticated;

