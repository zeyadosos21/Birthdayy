create or replace function public.get_gallery_categories(p_code text)
returns table(id bigint,name text,sort_order integer)
language plpgsql security definer set search_path=public,extensions
as $$
begin
  if not public.verify_site_code(p_code) then raise exception 'Wrong birthday password'; end if;
  return query select c.id,c.name,c.sort_order from public.gallery_categories c order by c.sort_order,c.id;
end; $$;
revoke execute on function public.get_gallery_categories(text) from public;
grant execute on function public.get_gallery_categories(text) to anon, authenticated;

create or replace function public.get_gallery_media(p_code text)
returns table(id bigint,category_id bigint,category_name text,media_type text,storage_path text,caption text,sort_order integer)
language plpgsql security definer set search_path=public,extensions
as $$
begin
  if not public.verify_site_code(p_code) then raise exception 'Wrong birthday password'; end if;
  return query
    select m.id,m.category_id,c.name,m.media_type,m.storage_path,m.caption,m.sort_order
    from public.gallery_media m join public.gallery_categories c on c.id=m.category_id
    order by m.sort_order,m.id;
end; $$;
revoke execute on function public.get_gallery_media(text) from public;
