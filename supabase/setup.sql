-- ============================================================
-- PASSWORD CHECK
-- ============================================================
create or replace function public.verify_site_code(p_code text)
returns boolean
language sql
security definer
set search_path = public, extensions
as $$
  select exists (
    select 1 from public.birthday_settings
    where id=1
      and encode(digest(convert_to(coalesce(p_code,''),'UTF8'),'sha256'),'hex') = code_hash
  );
$$;
revoke execute on function public.verify_site_code(text) from public;
grant execute on function public.verify_site_code(text) to anon, authenticated;

-- ============================================================
-- OWNER CHECK
-- ============================================================
create or replace function public.is_birthday_owner()
returns boolean
language sql
security definer
set search_path = public
as $$
  select auth.uid() is not null
     and exists (select 1 from public.birthday_admins where user_id=auth.uid());
$$;
revoke execute on function public.is_birthday_owner() from public;
grant execute on function public.is_birthday_owner() to authenticated;

