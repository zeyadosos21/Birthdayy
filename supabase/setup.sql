create or replace function public.owner_set_site_code(p_code text)
returns void
language plpgsql security definer set search_path=public,extensions
as $$
begin
  if not public.is_birthday_owner() then raise exception 'Owner only'; end if;
  if p_code !~ '^[0-9]{4}$' then raise exception 'PIN must be exactly 4 digits'; end if;
  update public.birthday_settings
  set code_hash=encode(digest(convert_to(p_code,'UTF8'),'sha256'),'hex'), updated_at=now()
  where id=1;
end; $$;
revoke execute on function public.owner_set_site_code(text) from public;
grant execute on function public.owner_set_site_code(text) to authenticated;

